#!/usr/bin/env python3
"""Generate Go API constants from the Rust source of truth."""

import re
import subprocess
from pathlib import Path

here = Path(__file__).resolve().parent
rust = here.parents[2] / "crates/wampproto/src"


def camel(value):
    return "".join(
        {"uri": "URI", "id": "ID", "goodbye": "GoodBye"}.get(part, part.title()) for part in value.split("_")
    )


constants = {}
for name, value in re.findall(r'pub const (\w+): &str = "([^"]+)";', (rust / "options.rs").read_text()):
    public = camel(name.lower())
    if name == "OPTION_ACKNOWLEDGE":
        public = "OptAcknowledge"
    constants[public] = value
for _, value in re.findall(r'pub const (\w+): &str = "([^"]+)";', (rust / "uris.rs").read_text()):
    category, suffix = value.split(".", 2)[1:]
    constants[("Err" if category == "error" else "Close") + camel(suffix.replace(".", "_"))] = value
out = "// Code generated by generate.py from Rust protocol constants. DO NOT EDIT.\npackage protocol\n\nconst (\n"
out += "".join(f'{key} = "{value}"\n' for key, value in sorted(constants.items())) + ")\n"
(here / "constants.go").write_text(out)
subprocess.run(["gofmt", "-w", str(here / "constants.go")], check=True)
