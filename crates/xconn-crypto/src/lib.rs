//! Portable packet encryption, independent of transport and application policy.
//!
//! X25519 does not authenticate a peer. The application must establish trust in
//! the peer key through its authenticated session or another trusted mechanism.
//! Associated data can bind application context to each encrypted packet.
use chacha20poly1305::{
    ChaCha20Poly1305, KeyInit, Nonce,
    aead::{Aead, Payload},
};
use hkdf::Hkdf;
use rand_core::{OsRng, RngCore};
use sha2::Sha256;
use x25519_dalek::{PublicKey, StaticSecret};
use zeroize::Zeroizing;

pub const KEY_SIZE: usize = 32;
pub const NONCE_SIZE: usize = 12;
const TAG_SIZE: usize = 16;

#[derive(Debug)]
pub struct Error(String);

impl std::fmt::Display for Error {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(&self.0)
    }
}
impl std::error::Error for Error {}

pub struct KeyPair {
    pub public: [u8; KEY_SIZE],
    pub private: Zeroizing<[u8; KEY_SIZE]>,
}

pub fn generate_key_pair() -> Result<KeyPair, Error> {
    let mut private = Zeroizing::new([0; KEY_SIZE]);
    OsRng
        .try_fill_bytes(private.as_mut())
        .map_err(|error| Error(format!("key generation failed: {error}")))?;
    let public = PublicKey::from(&StaticSecret::from(*private));
    Ok(KeyPair {
        public: public.to_bytes(),
        private,
    })
}

pub fn shared_secret(private: &[u8], public: &[u8]) -> Result<Zeroizing<[u8; KEY_SIZE]>, Error> {
    let private: [u8; KEY_SIZE] = private
        .try_into()
        .map_err(|_| Error(format!("invalid private key length: {}", private.len())))?;
    let public: [u8; KEY_SIZE] = public
        .try_into()
        .map_err(|_| Error(format!("invalid public key length: {}", public.len())))?;
    let private = StaticSecret::from(private);
    let secret = private.diffie_hellman(&PublicKey::from(public));
    if !secret.was_contributory() {
        return Err(Error("computed shared secret is weak (all zeros)".into()));
    }
    Ok(Zeroizing::new(secret.to_bytes()))
}

pub fn derive_key(secret: &[u8], info: &[u8]) -> Result<Zeroizing<[u8; KEY_SIZE]>, Error> {
    let mut key = Zeroizing::new([0; KEY_SIZE]);
    Hkdf::<Sha256>::new(None, secret)
        .expand(info, key.as_mut())
        .map_err(|_| Error("key derivation failed".into()))?;
    Ok(key)
}

/// Returns nonce || ciphertext || authentication tag. Nonces are generated by
/// the OS CSPRNG (browser cryptographic randomness when compiled for WASM).
pub fn encrypt(plaintext: &[u8], key: &[u8], additional_data: &[u8]) -> Result<Vec<u8>, Error> {
    let cipher = ChaCha20Poly1305::new_from_slice(key).map_err(|_| Error("invalid encryption key length".into()))?;
    let mut nonce = [0; NONCE_SIZE];
    OsRng
        .try_fill_bytes(&mut nonce)
        .map_err(|error| Error(format!("nonce generation failed: {error}")))?;
    let ciphertext = cipher
        .encrypt(
            Nonce::from_slice(&nonce),
            Payload {
                msg: plaintext,
                aad: additional_data,
            },
        )
        .map_err(|_| Error("encryption failed".into()))?;
    let mut packet = Vec::with_capacity(NONCE_SIZE + ciphertext.len());
    packet.extend_from_slice(&nonce);
    packet.extend_from_slice(&ciphertext);
    Ok(packet)
}

pub fn decrypt(packet: &[u8], key: &[u8], additional_data: &[u8]) -> Result<Vec<u8>, Error> {
    if packet.len() < NONCE_SIZE + TAG_SIZE {
        return Err(Error(format!("payload too short: {} bytes", packet.len())));
    }
    let cipher = ChaCha20Poly1305::new_from_slice(key).map_err(|_| Error("invalid encryption key length".into()))?;
    cipher
        .decrypt(
            Nonce::from_slice(&packet[..NONCE_SIZE]),
            Payload {
                msg: &packet[NONCE_SIZE..],
                aad: additional_data,
            },
        )
        .map_err(|_| Error("decryption failed".into()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn decrypts_packets_and_derives_keys_from_the_independent_go_implementation() {
        let fixture: std::collections::HashMap<String, String> =
            serde_json::from_str(include_str!("../tests/fixtures/go-reference.json")).unwrap();
        let bytes = |key: &str| hex::decode(&fixture[key]).unwrap();
        let secret = shared_secret(&bytes("private"), &bytes("public")).unwrap();
        assert_eq!(secret.as_ref(), bytes("shared"));
        let key = derive_key(secret.as_ref(), &bytes("info")).unwrap();
        assert_eq!(key.as_ref(), bytes("key"));
        assert_eq!(
            decrypt(&bytes("packet"), key.as_ref(), &bytes("aad")).unwrap(),
            bytes("plaintext")
        );
    }

    #[test]
    fn key_exchange_and_directional_keys_agree() {
        let client = generate_key_pair().unwrap();
        let server = generate_key_pair().unwrap();
        let first = shared_secret(client.private.as_ref(), &server.public).unwrap();
        let second = shared_secret(server.private.as_ref(), &client.public).unwrap();
        assert_eq!(first, second);
        assert_ne!(
            derive_key(first.as_ref(), b"client-to-server").unwrap(),
            derive_key(second.as_ref(), b"server-to-client").unwrap()
        );
        assert!(shared_secret(client.private.as_ref(), &[0; KEY_SIZE]).is_err());
    }

    #[test]
    fn rejects_modified_packets_keys_and_context() {
        let key = derive_key(b"shared secret", b"example context").unwrap();
        let packet = encrypt(b"hello", key.as_ref(), b"shell").unwrap();
        assert_eq!(decrypt(&packet, key.as_ref(), b"shell").unwrap(), b"hello");
        assert!(decrypt(&packet, key.as_ref(), b"file").is_err());
        assert!(decrypt(&packet, &[1; KEY_SIZE], b"shell").is_err());
        let mut modified = packet;
        modified[NONCE_SIZE] ^= 1;
        assert!(decrypt(&modified, key.as_ref(), b"shell").is_err());
        assert!(decrypt(&[0; NONCE_SIZE], key.as_ref(), b"shell").is_err());
    }
}
